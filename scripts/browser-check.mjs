import assert from 'node:assert/strict';
import {chromium} from 'playwright';
import fs from 'node:fs';
const chrome=process.env.BROWSER_EXECUTABLE_PATH??'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const browser=await chromium.launch({headless:true,...(fs.existsSync(chrome)?{executablePath:chrome}:{})});
const page=await browser.newPage({viewport:{width:1512,height:1080},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5173/',{waitUntil:'networkidle'});
await page.getByRole('row',{name:'选择沪深300ETF华泰柏瑞'}).waitFor();
await page.locator('canvas').first().waitFor({timeout:20000});
assert.equal(await page.locator('.watch-panel .ant-table-row').count(),8);
await page.screenshot({path:'artifacts/desktop-live.png',fullPage:true});
console.log('INITIAL',JSON.stringify({title:await page.title(),rows:await page.locator('.watch-panel .ant-table-row').count(),canvas:await page.locator('canvas').count(),bodyOverflow:await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),errors}));
await page.getByRole('textbox',{name:'搜索ETF'}).fill('创业板');
assert.equal(await page.locator('.watch-panel .ant-table-row').count(),2);
console.log('SEARCH',await page.locator('.watch-panel .ant-table-row').count());
await page.getByRole('textbox',{name:'搜索ETF'}).fill('');
await page.getByRole('row',{name:'选择创业板ETF易方达'}).click();
await page.waitForTimeout(700);
console.log('SELECT',await page.locator('.chart-price-row').innerText());
await page.getByRole('button',{name:'管理关注'}).click();
await page.getByRole('button',{name:/完\s*成/}).click();
await page.getByRole('menuitem').filter({hasText:'预警中心'}).click();
await page.getByRole('button',{name:/预警规则/}).click();
await page.getByRole('spinbutton',{name:'超卖阈值'}).fill('25');
await page.getByRole('button',{name:'保存规则'}).click();
console.log('SETTINGS',await page.evaluate(()=>JSON.parse(localStorage.getItem('guanlan.rules.v1'))));
await page.getByRole('menuitem').filter({hasText:'机构持仓'}).click();
await page.locator('.holdings-panel .ant-table-row').first().waitFor({timeout:20000});
await page.screenshot({path:'artifacts/holdings-live.png',fullPage:true});
console.log('HOLDERS',await page.locator('.holdings-panel .holding-summary').innerText());
await page.getByRole('menuitem').filter({hasText:'市场概览'}).click();
assert.equal(await page.getByText('演示模式',{exact:true}).count(),0);
await page.waitForTimeout(3200);
await page.setViewportSize({width:390,height:844});
await page.waitForTimeout(350);
await page.screenshot({path:'artifacts/mobile-live.png',fullPage:true});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
console.log('MOBILE',JSON.stringify({overflow:await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),errors}));
await page.getByRole('button',{name:'打开导航'}).click();
await page.getByRole('menuitem').filter({hasText:'数据与设置'}).click();
await page.waitForTimeout(350);
await page.screenshot({path:'artifacts/mobile-settings.png',fullPage:true});
await browser.close();
assert.deepEqual(errors,[]);
